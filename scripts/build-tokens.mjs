// Builds design tokens (src/tokens/source/*.json, DTCG format) with Style Dictionary.
// Output in src/tokens/generated:
//   tokens.css -> `--wfo-*` CSS variables: light on :root, dark colors on :root[data-wfo-color-mode='dark'].
//                 Before the app sets the attribute (first paint), the OS setting decides.
//   tokens.ts  -> typed `var(--wfo-*)` references for the rare case JS needs a token
import { mkdirSync, writeFileSync } from 'node:fs';
import StyleDictionary from 'style-dictionary';

const OUTPUT_DIRECTORY = 'src/tokens/generated';
const DARK_SELECTOR = ":root[data-wfo-color-mode='dark']";
const SYSTEM_DARK_SELECTOR = ":root:not([data-wfo-color-mode='light'])";
const MODE_DEPENDENT_GROUPS = ['color', 'shadow'];
const toCamelCase = (path) =>
  path.map((part, index) => (index ? part[0].toUpperCase() + part.slice(1) : part)).join('');

async function buildTokens(mode) {
  const styleDictionary = new StyleDictionary({
    source: ['src/tokens/source/base.json', `src/tokens/source/color.${mode}.json`],
    log: { verbosity: 'silent' },
    platforms: { css: { transformGroup: 'css', prefix: 'wfo' } },
  });
  const platformTokens = await styleDictionary.getPlatformTokens('css');
  return platformTokens.allTokens.map((token) => ({
    name: `--${token.name}`,
    value: token.$value ?? token.value,
    path: token.path,
  }));
}

const toDeclarations = (tokens) => tokens.map((token) => `  ${token.name}: ${token.value};`).join('\n');

const [lightTokens, darkTokens] = await Promise.all([buildTokens('light'), buildTokens('dark')]);
const darkOnlyTokens = darkTokens.filter((token) => MODE_DEPENDENT_GROUPS.includes(token.path[0]));
const tokenReferences = lightTokens.map((token) => `  ${toCamelCase(token.path)}: 'var(${token.name})',`).join('\n');

mkdirSync(OUTPUT_DIRECTORY, { recursive: true });
writeFileSync(
  `${OUTPUT_DIRECTORY}/tokens.css`,
  `/* GENERATED by scripts/build-tokens.mjs from src/tokens/source. Do not edit. */
:root {
${toDeclarations(lightTokens)}
}

@media (prefers-color-scheme: dark) {
  ${SYSTEM_DARK_SELECTOR} {
${toDeclarations(darkOnlyTokens).replace(/^/gm, '  ')}
  }
}

${DARK_SELECTOR} {
${toDeclarations(darkOnlyTokens)}
}
`,
);
writeFileSync(
  `${OUTPUT_DIRECTORY}/tokens.ts`,
  `// GENERATED by scripts/build-tokens.mjs from src/tokens/source. Do not edit.
/** Prefer \`var(--wfo-*)\` in a CSS module. Use this only when JavaScript needs a token. */
export const wfoTokens = {
${tokenReferences}
} as const;
`,
);
console.log(`tokens built: ${lightTokens.length} light, ${darkOnlyTokens.length} dark-only`);
